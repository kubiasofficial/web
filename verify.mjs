import { spawn } from 'node:child_process';
import { mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.dirname(fileURLToPath(import.meta.url));
const qa = path.resolve(root,'../.qa'); mkdirSync(qa,{recursive:true});
const debugPort=9500+process.pid%1000;
const chrome = spawn('C:/Program Files/Google/Chrome/Application/chrome.exe', ['--headless=new','--disable-gpu','--no-first-run','--no-default-browser-check','--remote-allow-origins=*',`--remote-debugging-port=${debugPort}`,`--user-data-dir=${qa}/chrome-${debugPort}`,'about:blank'],{windowsHide:true,stdio:['ignore','ignore','pipe']});
chrome.stderr.on('data',chunk=>{if(String(chunk).includes('ERROR'))process.stderr.write(chunk);});
const sleep = ms => new Promise(r=>setTimeout(r,ms));
let ws, nextId=0; const pending=new Map();
const keepAlive=setInterval(()=>{},1000);
try {
 let tabs;
 for(let i=0;i<60;i++){try{tabs=await (await fetch(`http://127.0.0.1:${debugPort}/json/list`)).json();if(tabs.some(t=>t.type==='page'))break;}catch{}await sleep(250);}
 if(!tabs) throw Error('Browser debugging endpoint unavailable');
 ws = new WebSocket(tabs.find(t=>t.type==='page').webSocketDebuggerUrl);
 await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject;});
 ws.onmessage = event => {const msg=JSON.parse(event.data);if(msg.id){const task=pending.get(msg.id);pending.delete(msg.id);msg.error?task.reject(Error(JSON.stringify(msg.error))):task.resolve(msg.result);}};
 const send=(method,params={})=>new Promise((resolve,reject)=>{const id=++nextId;const timer=setTimeout(()=>{pending.delete(id);reject(Error('CDP timed out: '+method));},10000);pending.set(id,{resolve:value=>{clearTimeout(timer);resolve(value);},reject:error=>{clearTimeout(timer);reject(error);}});ws.send(JSON.stringify({id,method,params}));});
 const evaluate=async expression=>(await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true})).result.value;
 const assert=(condition,message)=>{if(!condition)throw Error(message);console.log('PASS '+message);};
 await send('Page.enable');
 await send('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
 await send('Page.navigate',{url:new URL('file:///'+root.replaceAll('\\','/')+'/dist/index.html').href});
 await sleep(1800);
 assert(await evaluate('document.querySelectorAll(".hotspot").length===5'),'Five clickable poster regions');
 assert(await evaluate('document.querySelector(".poster-image").naturalWidth>0'),'Original poster loaded');
 assert(await evaluate('!document.querySelector("dialog").open'),'Intro shows only poster');
 assert(await evaluate('document.documentElement.scrollWidth<=innerWidth'),'Desktop no overflow');
 const hit = await evaluate('JSON.stringify((()=>{const r=document.querySelector(".poster").getBoundingClientRect();return {x:r.x+r.width*.5,y:r.y+r.height*.3}})())');
 const point=JSON.parse(hit);
 assert(await evaluate(`document.elementFromPoint(${point.x},${point.y}).classList.contains('nathaniel')`),'Nathaniel hit area matches original portrait');
 await send('Input.dispatchMouseEvent',{type:'mouseMoved',...point});await sleep(300);
 assert(await evaluate('getComputedStyle(document.querySelector(".nathaniel"),"::before").opacity==="1"'),'Hover lights Nathaniel');
 const {writeFileSync}=await import('node:fs');
 let shot=await send('Page.captureScreenshot',{format:'png'});writeFileSync(path.join(qa,'poster-hover.png'),Buffer.from(shot.data,'base64'));
 await send('Input.dispatchMouseEvent',{type:'mousePressed',button:'left',clickCount:1,...point});
 await send('Input.dispatchMouseEvent',{type:'mouseReleased',button:'left',clickCount:1,...point});await sleep(200);
 assert(await evaluate('document.querySelector("dialog").open'),'Click on portrait opens lore');
 assert(await evaluate('document.querySelectorAll("#story section").length===11 && document.querySelector("#story").textContent.includes("Kdo ho zradil?")'),'Complete Nathaniel lore displayed');
 shot=await send('Page.captureScreenshot',{format:'png'});writeFileSync(path.join(qa,'poster-lore.png'),Buffer.from(shot.data,'base64'));
 await send('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
 await send('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
 assert(await evaluate('!document.querySelector("dialog").open'),'Escape returns to poster');
 await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
 await evaluate('document.querySelector(".nathaniel").click()');await sleep(150);
 assert(await evaluate('document.querySelector("dialog").scrollWidth<=document.querySelector("dialog").clientWidth'),'Mobile lore no overflow');
 await evaluate('document.querySelector(".close").click()');
 assert(await evaluate('!document.querySelector("dialog").open'),'Close button returns to poster');
 await evaluate('document.querySelector(".scarlet").click()');
 assert(await evaluate('!document.querySelector("#notice").hidden'),'Unfinished characters show preparation notice');
 console.log('Screenshots saved in '+qa);
 await send('Browser.close');
}finally{clearInterval(keepAlive);ws?.close();chrome.kill();}
