import { spawn } from 'node:child_process';
import { mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.dirname(fileURLToPath(import.meta.url));
const qa = path.resolve(root,'../.qa'); mkdirSync(qa,{recursive:true});
const debugPort=9500+process.pid%1000;
const chrome = spawn('C:/Program Files/Google/Chrome/Application/chrome.exe', ['--headless=new','--disable-gpu','--no-first-run','--no-default-browser-check','--remote-allow-origins=*',`--remote-debugging-port=${debugPort}`,`--user-data-dir=${qa}/chrome-${debugPort}`,'about:blank'],{windowsHide:true,stdio:['ignore','ignore','pipe']});
chrome.stderr.on('data',chunk=>{if(String(chunk).includes('ERROR'))process.stderr.write(chunk);});
const sleep = ms => new Promise(r=>setTimeout(r,ms));
let ws, nextId=0; const pending=new Map();
const keepAlive=setInterval(()=>{},1000);
try {
 let tabs;
 for(let i=0;i<60;i++){try{tabs=await (await fetch(`http://127.0.0.1:${debugPort}/json/list`)).json();if(tabs.some(t=>t.type==='page'))break;}catch{}await sleep(250);}
 if(!tabs) throw Error('Browser debugging endpoint unavailable');
 ws = new WebSocket(tabs.find(t=>t.type==='page').webSocketDebuggerUrl);
 await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject;});
 ws.onmessage = event => {const msg=JSON.parse(event.data);if(msg.id){const task=pending.get(msg.id);pending.delete(msg.id);msg.error?task.reject(Error(JSON.stringify(msg.error))):task.resolve(msg.result);}};
 const send=(method,params={})=>new Promise((resolve,reject)=>{const id=++nextId;const timer=setTimeout(()=>{pending.delete(id);reject(Error('CDP timed out: '+method));},10000);pending.set(id,{resolve:value=>{clearTimeout(timer);resolve(value);},reject:error=>{clearTimeout(timer);reject(error);}});ws.send(JSON.stringify({id,method,params}));});
 const evaluate=async expression=>(await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true})).result.value;
 const assert=(condition,message)=>{if(!condition)throw Error(message);console.log('PASS '+message);};
 await send('Page.enable');
 await send('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
 await send('Page.navigate',{url:new URL('file:///'+root.replaceAll('\\','/')+'/dist/index.html').href});
 await sleep(1800);
 assert(await evaluate('document.querySelectorAll(".story-chapter").length===11'),'All 11 lore sections rendered');
 assert(await evaluate('!document.querySelector("#home").hidden && document.querySelector("#profile").hidden'),'Home route shows selection');
 assert(await evaluate('document.documentElement.scrollWidth <= innerWidth'),'Desktop has no horizontal overflow');
 await evaluate('document.querySelector(".nathaniel").click()'); await sleep(200);
 assert(await evaluate('!document.querySelector("#profile").hidden && document.querySelector("#home").hidden'),'Character button opens Nathaniel');
 assert(await evaluate('document.querySelector("#story").textContent.includes("Kdo ho zradil?")'),'Original betrayal chapter present');
 assert(await evaluate('document.querySelector(".profile-cutout").complete && document.querySelector(".profile-cutout").naturalWidth===1024'),'Character asset loaded');
 await evaluate('document.querySelector("#chapter-nav a:nth-child(4)").click()');await sleep(200);
 assert(await evaluate('location.hash==="#kapitola-4" && !document.querySelector("#profile").hidden'),'Chapter deep link works');
 const desktop = await send('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
 const {writeFileSync}=await import('node:fs');writeFileSync(path.join(qa,'desktop-story.png'),Buffer.from(desktop.data,'base64'));
 await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
 await evaluate('location.hash="#nathaniel"');await sleep(250);
 assert(await evaluate('document.documentElement.scrollWidth<=innerWidth'),'Mobile profile has no horizontal overflow');
 assert(await evaluate('scrollY===0'),'Opening profile returns to its beginning');
 const shot=await send('Page.captureScreenshot',{format:'png'});writeFileSync(path.join(qa,'mobile-profile.png'),Buffer.from(shot.data,'base64'));
 await evaluate('document.querySelector(".back").click()');await sleep(250);
 assert(await evaluate('!document.querySelector("#home").hidden'),'Back button restores character selection');
 assert(await evaluate('document.documentElement.scrollWidth<=innerWidth'),'Mobile home has no horizontal overflow');
 await evaluate('document.querySelector(".pending").click()');
 assert(await evaluate('document.querySelector("#cast-message").textContent.includes("Scarlet Sky Raven")'),'Pending character gives clear feedback');
 await send('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});await evaluate('location.hash=""');await sleep(250);
 const homeShot=await send('Page.captureScreenshot',{format:'png',captureBeyondViewport:true});writeFileSync(path.join(qa,'desktop-home.png'),Buffer.from(homeShot.data,'base64'));
 console.log('Screenshots saved in '+qa);
 await send('Browser.close');
}finally{clearInterval(keepAlive);ws?.close();chrome.kill();}
